def make_notebook(topic: str, exercises: list[str]) -> dict:
    cells = [
        {
            "cell_type": "markdown",
            "id": "intro",
            "metadata": {},
            "source": [
                f"# Εξάσκηση: {topic}\n",
                "Απαντήστε σε κάθε ερώτηση γράφοντας ένα πρόγραμμα Python που λύνει το συγκεκριμένο πρόβλημα. "
                "Γράψτε την απάντησή σας στο κενό κελί κώδικα κάτω από κάθε ερώτημα.\n"
            ],
        }
    ]
    for i, prompt in enumerate(exercises, 1):
        num = f"{i:02d}"
        cells.append(
            {
                "cell_type": "markdown",
                "id": f"ex{num}",
                "metadata": {},
                "source": [f"## Άσκηση {i}\n", prompt],
            }
        )
        cells.append(
            {
                "cell_type": "code",
                "execution_count": None,
                "id": f"code{num}",
                "metadata": {},
                "outputs": [],
                "source": [],
            }
        )
    return {
        "cells": cells,
        "metadata": {"language_info": {"name": "python"}},
        "nbformat": 4,
        "nbformat_minor": 5,
    }

