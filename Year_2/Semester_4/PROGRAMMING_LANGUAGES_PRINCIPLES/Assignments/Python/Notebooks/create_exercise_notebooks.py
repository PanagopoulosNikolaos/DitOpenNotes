def makeNotebook(topic: str, exercises: list[str]) -> dict:
    """
    Creates a Jupyter notebook structure with markdown descriptions and code cells.

    Args:
        topic (str): The subject matter title for the notebook.
        exercises (list[str]): List of markdown strings for individual exercise prompts.

    Returns:
        dict: Notebook JSON dictionary structure.
    """
    cells = [
        {
            "cell_type": "markdown",
            "id": "intro",
            "metadata": {},
            "source": [
                f"# Εξάσκηση: {topic}\n",
                "\n",
                "Απαντήστε σε κάθε ερώτηση γράφοντας ένα πρόγραμμα Python που λύνει το συγκεκριμένο πρόβλημα. "
                "Γράψτε την απάντησή σας στο κενό κελί κώδικα κάτω από κάθε ερώτημα.\n",
                "\n",
                "**Στυλ Πανεπιστημίου**: Δώστε προσοχή στις προδιαγραφές, στα παραδείγματα εισόδου/εξόδου και στις ακραίες περιπτώσεις (edge cases). "
                "Χρησιμοποιήστε σχόλια στον κώδικα για να εξηγήσετε τις αποφάσεις σας.\n"
            ],
        }
    ]
    for i, prompt in enumerate(exercises, 1):
        num = f"{i:02d}"
        cells.append(
            {
                "cell_type": "markdown",
                "id": f"ex{num}",
                "metadata": {},
                "source": [f"## Άσκηση {i}\n", prompt],
            }
        )
        cells.append(
            {
                "cell_type": "code",
                "execution_count": None,
                "id": f"code{num}",
                "metadata": {},
                "outputs": [],
                "source": [],
            }
        )
    return {
        "cells": cells,
        "metadata": {
            "language_info": {"name": "python", "version": "3.12"},
            "kernelspec": {"name": "python3", "display_name": "Python 3"}
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }

